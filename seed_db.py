"""Load the RevoShop / RevoTech sample data through SQLAlchemy.

The data lives in seed_data.json, generated by the RevoTech storefront
(`node scripts/export-seed.mjs`) from its catalogue, so product names, prices,
specs and image paths always match the storefront's product photos:
6 kategori, 23 produk (harga dalam rupiah), 6 user, 6 order dan 15 order item,
plus konten homepage/About dan pengaturan toko. Jalankan setelah `flask db upgrade`.

    python seed_db.py

DESTRUCTIVE: semua tabel dikosongkan lebih dulu (truncate ... restart identity),
jadi aman dijalankan berulang kali -- tetapi jangan pernah terhadap database yang
datanya ingin disimpan. Backup dulu (pg_dump) sebelum menjalankannya di Supabase.

Every seeded account shares the demo password below:
    andi.pratama@example.com   superadmin
    budi.santoso@example.com   admin
    siti, dewi, rizky, maya    customer
"""

import json
from decimal import Decimal
from pathlib import Path

from werkzeug.security import generate_password_hash

from app import app
from models import Category, Order, Product, SiteContent, SiteSettings, User, db, order_items

SEED_FILE = Path(__file__).with_name("seed_data.json")

# Every seeded user shares this password so login can be demonstrated.
SEED_PASSWORD = "password123"

TABLES = "order_items, orders, products, categories, users, site_content, site_settings"


def clear():
    """Wipe the tables and restart the identity sequences."""
    db.session.execute(db.text(f"truncate table {TABLES} restart identity cascade"))
    db.session.commit()


def seed(data):
    clear()
    password_hash = generate_password_hash(SEED_PASSWORD)

    db.session.add_all(
        User(
            id=u["id"],
            username=u["username"],
            email=u["email"],
            password_hash=password_hash,
            phone_number=u["phone_number"],
            address=u["address"],
            role=u["role"],
        )
        for u in data["users"]
    )
    db.session.add_all(
        Category(category_id=c["category_id"], category_name=c["category_name"], description=c["description"])
        for c in data["categories"]
    )
    db.session.flush()

    db.session.add_all(
        Product(
            product_id=p["product_id"],
            category_id=p["category_id"],
            product_name=p["product_name"],
            description=p["description"],
            price=Decimal(str(p["price"])),
            stock_quantity=p["stock_quantity"],
            is_active=p["is_active"],
            official_url=p["official_url"],
            overview=p["overview"],
            overview_source=p["overview_source"],
            images=p["images"],
            specs=p["specs"],
            specs_source=p["specs_source"],
        )
        for p in data["products"]
    )
    db.session.flush()

    for o in data["orders"]:
        total = sum(Decimal(str(i["unit_price"])) * i["quantity"] for i in o["items"])
        db.session.add(
            Order(
                order_id=o["order_id"],
                user_id=o["user_id"],
                order_status=o["order_status"],
                shipping_address=o["shipping_address"],
                ordered_at=o["ordered_at"],
                total_amount=total,
            )
        )
    db.session.flush()
    db.session.execute(
        order_items.insert(),
        [
            {
                "order_id": o["order_id"],
                "product_id": i["product_id"],
                "quantity": i["quantity"],
                "unit_price": Decimal(str(i["unit_price"])),
            }
            for o in data["orders"]
            for i in o["items"]
        ],
    )

    db.session.add_all(SiteContent(key=key, content=doc) for key, doc in data["content"].items())
    db.session.add(SiteSettings(id=1, settings=data["settings"], logo=None))

    # The rows above were inserted with explicit ids, so move each sequence past the
    # highest one -- otherwise the next INSERT would collide with a seeded id.
    for table, column in [
        ("users", "id"),
        ("categories", "category_id"),
        ("products", "product_id"),
        ("orders", "order_id"),
        ("order_items", "order_item_id"),
    ]:
        db.session.execute(
            db.text(f"select setval(pg_get_serial_sequence('{table}', '{column}'), (select max({column}) from {table}))")
        )
    db.session.commit()


def report():
    for label, model in [
        ("users", User),
        ("categories", Category),
        ("products", Product),
        ("orders", Order),
        ("site_content", SiteContent),
        ("site_settings", SiteSettings),
    ]:
        count = db.session.query(db.func.count()).select_from(model).scalar()
        print(f"  {label:<14} {count}")
    item_count = db.session.execute(db.select(db.func.count()).select_from(order_items)).scalar()
    print(f"  {'order_items':<14} {item_count}")


if __name__ == "__main__":
    with app.app_context():
        seed(json.loads(SEED_FILE.read_text(encoding="utf-8")))
        print(f"seeded {db.engine.url.render_as_string(hide_password=True)}:")
        report()
